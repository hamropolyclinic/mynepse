/**
 * Updates a stock in the local directory with live price information
 */
export function updateStockInDirectory(stock: StockFundamental): void {
  const upper = stock.symbol.toUpperCase();
  const idx = NEPSE_STOCK_DIRECTORY.findIndex((s) => s.symbol === upper);
  if (idx >= 0) {
    NEPSE_STOCK_DIRECTORY[idx] = {
      ...NEPSE_STOCK_DIRECTORY[idx],
      ...stock,
      symbol: upper,
    };
  } else {
    NEPSE_STOCK_DIRECTORY.push({
      ...stock,
      symbol: upper,
    });
  }
}

